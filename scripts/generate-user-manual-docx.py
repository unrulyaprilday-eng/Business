def esc(text):
    return html.escape(str(text), quote=False)


def p(text="", style=None):
    style_xml = f"<w:pPr><w:pStyle w:val=\"{style}\"/></w:pPr>" if style else ""
    return (
        "<w:p>"
        f"{style_xml}"
        "<w:r><w:rPr><w:rFonts w:eastAsia=\"Microsoft YaHei\" w:ascii=\"Arial\" w:hAnsi=\"Arial\"/></w:rPr>"
        f"<w:t xml:space=\"preserve\">{esc(text)}</w:t></w:r>"
        "</w:p>"
    )


def bookmark_p(text, bookmark, style=None):
    style_xml = f"<w:pPr><w:pStyle w:val=\"{style}\"/></w:pPr>" if style else ""
    return (
        "<w:p>"
        f"{style_xml}"
        f"<w:bookmarkStart w:id=\"{bookmark['id']}\" w:name=\"{bookmark['name']}\"/>"
        "<w:r><w:rPr><w:rFonts w:eastAsia=\"Microsoft YaHei\" w:ascii=\"Arial\" w:hAnsi=\"Arial\"/></w:rPr>"
        f"<w:t xml:space=\"preserve\">{esc(text)}</w:t></w:r>"
        f"<w:bookmarkEnd w:id=\"{bookmark['id']}\"/>"
        "</w:p>"
    )


def link_p(text, anchor, level=0):
    indent = 240 + level * 360
    return (
        "<w:p>"
        f"<w:pPr><w:ind w:left=\"{indent}\"/></w:pPr>"
        f"<w:hyperlink w:anchor=\"{anchor}\">"
        "<w:r><w:rPr><w:rStyle w:val=\"Hyperlink\"/><w:rFonts w:eastAsia=\"Microsoft YaHei\" w:ascii=\"Arial\" w:hAnsi=\"Arial\"/></w:rPr>"
        f"<w:t xml:space=\"preserve\">{esc(text)}</w:t></w:r>"
        "</w:hyperlink>"
        "</w:p>"
    )


def toc_field():
    return (
        "<w:p><w:r><w:fldChar w:fldCharType=\"begin\"/></w:r>"
        "<w:r><w:instrText xml:space=\"preserve\">TOC \\o \"1-3\" \\h \\z \\u</w:instrText></w:r>"
        "<w:r><w:fldChar w:fldCharType=\"separate\"/></w:r>"
        "<w:r><w:t>右键更新目录后显示页码</w:t></w:r>"
        "<w:r><w:fldChar w:fldCharType=\"end\"/></w:r></w:p>"
    )


def bullet(text):
    return (
        "<w:p><w:pPr><w:pStyle w:val=\"ListBullet\"/></w:pPr>"
        "<w:r><w:rPr><w:rFonts w:eastAsia=\"Microsoft YaHei\" w:ascii=\"Arial\" w:hAnsi=\"Arial\"/></w:rPr>"
        f"<w:t xml:space=\"preserve\">- {esc(text)}</w:t></w:r></w:p>"
    )


def page_doc(name, purpose, operation, note):
    return [
        p(name, "Heading3"),
        p(f"页面用途：{purpose}"),
        p(f"常用操作：{operation}"),
        p(f"使用要点：{note}"),
    ]


def qa(question, answer):
    return [
        p(question, "Heading3"),
        p(answer),
    ]


